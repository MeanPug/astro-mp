#!/usr/bin/env node
/**
 * Generates TypeScript types for every ACF block from the field groups in theme/acf-json.
 *
 *   npm run gen:types
 *
 * Output: src/lib/wp/blocks.generated.ts — one interface per "Block: X" group plus a
 * `BlockFieldsByName` map keyed by the block name (acf/<slug>). Select fields become
 * string unions, repeaters arrays, groups nested objects, image/link/file the shared
 * ACF value types from ./acf.ts (the shapes the astro/v1 endpoint returns).
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const acfJsonDir = process.env.ACF_JSON_DIR || resolve(here, '../../theme/acf-json');
const outFile = resolve(here, '../src/lib/wp/blocks.generated.ts');

const groups = readdirSync(acfJsonDir)
    .filter((f) => f.endsWith('.json'))
    .map((f) => JSON.parse(readFileSync(join(acfJsonDir, f), 'utf8')))
    .filter((g) => g.location?.some((rules) => rules.some((r) => r.param === 'block')));

const pascal = (s) =>
    s
        .replace(/^acf\//, '')
        .split(/[^a-zA-Z0-9]+/)
        .filter(Boolean)
        .map((w) => w[0].toUpperCase() + w.slice(1))
        .join('');

const quote = (s) => JSON.stringify(String(s));

function fieldType(field, indent) {
    switch (field.type) {
        case 'text':
        case 'textarea':
        case 'wysiwyg':
        case 'email':
        case 'url':
        case 'password':
        case 'oembed':
        case 'color_picker':
        case 'date_picker':
        case 'date_time_picker':
        case 'time_picker':
            return 'string';
        case 'number':
        case 'range':
            return 'number | string';
        case 'true_false':
            return 'boolean';
        case 'select':
        case 'radio':
        case 'button_group': {
            const values = Object.keys(field.choices || {}).map(quote);
            const union = values.length ? values.join(' | ') : 'string';
            return field.multiple ? `(${union})[]` : union;
        }
        case 'checkbox': {
            const values = Object.keys(field.choices || {}).map(quote);
            return `(${values.length ? values.join(' | ') : 'string'})[]`;
        }
        case 'image':
            return 'AcfImage | null';
        case 'file':
            return 'AcfFile | null';
        case 'gallery':
            return 'AcfImage[]';
        case 'link':
            return 'AcfLink | null';
        case 'google_map':
            return 'AcfGoogleMap | null';
        case 'post_object':
            return field.multiple ? 'AcfPostRef[]' : 'AcfPostRef | null';
        case 'relationship':
            return 'AcfPostRef[]';
        case 'taxonomy':
            return field.field_type === 'multi_select' || field.field_type === 'checkbox' ? 'AcfTermRef[]' : 'AcfTermRef | null';
        case 'user':
            return 'unknown';
        case 'group':
            return objectType(field.sub_fields || [], indent);
        case 'repeater':
        case 'flexible_content':
            return `${objectType(field.sub_fields || [], indent)}[]`;
        case 'clone':
            return 'Record<string, unknown>';
        default:
            return 'unknown';
    }
}

function objectType(fields, indent) {
    const pad = ' '.repeat(indent + 4);
    const lines = fields
        .filter((f) => f.type !== 'tab' && f.type !== 'message' && f.type !== 'accordion')
        .map((f) => {
            const doc = f.instructions ? `${pad}/** ${f.instructions.replace(/\s+/g, ' ').trim()} */\n` : '';
            return `${doc}${pad}${quote(f.name).replace(/^"([a-zA-Z_][a-zA-Z0-9_]*)"$/, '$1')}?: ${fieldType(f, indent + 4)};`;
        });
    return `{\n${lines.join('\n')}\n${' '.repeat(indent)}}`;
}

let out = '';

const map = [];
for (const group of groups.sort((a, b) => a.title.localeCompare(b.title))) {
    const rule = group.location.flat().find((r) => r.param === 'block');
    const blockName = rule.value;
    const typeName = `${pascal(blockName)}Fields`;
    out += `/** ${group.title} (${blockName}) */\nexport interface ${typeName} ${objectType(group.fields || [], 0)}\n\n`;
    map.push(`    ${quote(blockName)}: ${typeName};`);
}

out += `export interface BlockFieldsByName {\n${map.join('\n')}\n}\n\nexport type BlockName = keyof BlockFieldsByName;\n\nexport const BLOCK_NAMES = Object.freeze([\n${map
    .map((m) => `    ${m.trim().split(':')[0]},`)
    .join('\n')}\n] as const);\n`;

// only import the ACF value types the generated interfaces actually reference
const acfTypes = ['AcfFile', 'AcfGoogleMap', 'AcfImage', 'AcfLink', 'AcfPostRef', 'AcfTermRef'].filter((t) => new RegExp(`\\b${t}\\b`).test(out));
out = `// AUTO-GENERATED by scripts/gen-block-types.mjs from theme/acf-json. Do not edit.
${acfTypes.length ? `import type { ${acfTypes.join(', ')} } from './acf';\n` : ''}
${out}`;

writeFileSync(outFile, out);
console.log(`wrote ${outFile} (${groups.length} block groups)`);
